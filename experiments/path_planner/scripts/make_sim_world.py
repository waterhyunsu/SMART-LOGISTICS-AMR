#!/usr/bin/env python3
"""Convert the legacy Gazebo Classic lecture hall world into a Gazebo Harmonic (gz sim 8) world.

The legacy world is plain SDF boxes (walls, desks, chairs). Only its header is Classic-specific: the gazebo_ros
plugin and the model://ground_plane / model://sun includes. This script keeps every model as it is and replaces
the header with gz sim systems, an inline ground plane and a sun light, so the world needs no download.

    python3 experiments/path_planner/scripts/make_sim_world.py \
        experiments/path_planner/legacy_r1/worlds/lecture_hall_real.world \
        experiments/path_planner/sim/worlds/lecture_hall_real.sdf
"""

import os
import re
import sys

HEADER = """<?xml version="1.0"?>
<!-- Generated by scripts/make_sim_world.py from {source} (Gazebo Classic). Models are unchanged.
     [초안-팀합의필요] B 의 임시 주행 비교 환경이다. D 의 공식 월드·지도(P-014)가 나오면 그것으로 바꾼다. -->
<sdf version="1.8">
  <world name="{name}">
    <physics type="ode">
      <real_time_update_rate>1000.0</real_time_update_rate>
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <scene>
      <shadows>false</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material><ambient>0.8 0.8 0.8 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


def convert(source, target):
    with open(source, encoding='utf-8') as f:
        text = f.read()
    name = re.search(r'<world name="([^"]+)">', text).group(1)
    start = text.index('<model name=')          # the first model follows the Classic header
    body = text[start:]
    if 'libgazebo' in body or 'model://' in body:
        raise ValueError(f'{source}: Classic-only content after the header, convert it by hand')
    os.makedirs(os.path.dirname(os.path.abspath(target)), exist_ok=True)
    with open(target, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER.format(source=os.path.basename(source), name=name) + '    ' + body)
    return name, body.count('<model name=')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    world_name, models = convert(sys.argv[1], sys.argv[2])
    print(f'world {world_name}: {models} models -> {sys.argv[2]}')
